// Package assemble 是整书装配的确定性部分（旧线 assemble.go 逐字移植）。
// 会话编排（fixSession/finalReview）不进本包；这里只做纯文本/文件机械操作。
package assemble

import (
	"os"
	"path/filepath"
	"regexp"
	"strings"
)

// BuildStandaloneTex 生成单文件版：递归内联 \input/\include，图片仍是外部文件。
func BuildStandaloneTex(mainTexPath string) (string, error) {
	data, err := os.ReadFile(mainTexPath)
	if err != nil {
		return "", err
	}
	in := &standaloneInliner{root: filepath.Dir(mainTexPath), onStack: map[string]bool{}}
	body := in.expand(string(data), in.root, 0)
	header := "% standalone.tex — merged single-file version of the book project\n" +
		"% Generated by docvision skills; compile this file directly if needed.\n" +
		"% 章节与共享 tex 片段已全部内联；图片仍在 figures/ 等目录里（不是二进制内嵌）。\n"
	return header + body, nil
}

// standaloneInputMaxDepth 是内联层数的保险：子章节三层、加上垫片文与前端文件，
// 正常不会超过它；超过就停手，把剩下的 \input 原样留着。
const standaloneInputMaxDepth = 8

var reTexInput = regexp.MustCompile(`\\(?:input|include)\{([^}]+)\}`)

type standaloneInliner struct {
	root    string   // 构建树根（main.tex 所在目录）
	dirs    []string // 文档自己声明的 \input@path 搜索目录（相对构建树根）
	onStack map[string]bool
}

// expand 递归展开 body 里的 \input/\include。LaTeX 解析这类路径有三种来源，这里
// 按同样顺序找：包含它的那个文件的目录、构建树根、文档声明的 \input@path。
func (in *standaloneInliner) expand(body, fromDir string, depth int) string {
	in.collectInputPath(body)
	if depth > standaloneInputMaxDepth {
		return body
	}
	return reTexInput.ReplaceAllStringFunc(body, func(m string) string {
		sub := reTexInput.FindStringSubmatch(m)
		if len(sub) < 2 {
			return m
		}
		full, ok := in.resolve(strings.TrimSpace(sub[1]), fromDir)
		if !ok || in.onStack[full] {
			return m
		}
		inner, err := os.ReadFile(full)
		if err != nil {
			return m
		}
		in.onStack[full] = true
		inlined := in.expand(string(inner), filepath.Dir(full), depth+1)
		delete(in.onStack, full)
		rel, rerr := filepath.Rel(in.root, full)
		if rerr != nil {
			rel = full
		}
		return "% ==== " + filepath.ToSlash(rel) + " ====\n" + inlined
	})
}

// resolve 把一个 \input 目标落到磁盘上的 .tex 文件；只在构建树内找。
func (in *standaloneInliner) resolve(name, fromDir string) (string, bool) {
	rel := filepath.Clean(filepath.FromSlash(name))
	if rel == "." || filepath.IsAbs(rel) {
		return "", false
	}
	bases := []string{fromDir, in.root}
	for _, d := range in.dirs {
		bases = append(bases, filepath.Join(in.root, filepath.FromSlash(d)))
	}
	for _, base := range bases {
		cand := filepath.Join(base, rel)
		if !withinRoot(in.root, cand) {
			continue
		}
		for _, try := range []string{cand, cand + ".tex"} {
			if info, err := os.Stat(try); err == nil && !info.IsDir() {
				return try, true
			}
		}
	}
	return "", false
}

// collectInputPath 记下文档声明的 \input@path{{a/}{b/}}：章节用它把子章节的分片
// 目录挂进搜索路径，里面的 \input 就是裸的相对名字，靠这张表才找得到。
func (in *standaloneInliner) collectInputPath(body string) {
	const marker = "\\input@path"
	for i := 0; ; {
		j := strings.Index(body[i:], marker)
		if j < 0 {
			return
		}
		j += i + len(marker)
		k := strings.IndexByte(body[j:], '{')
		if k < 0 {
			return
		}
		k += j
		depth, entry := 0, strings.Builder{}
		for p := k; p < len(body); p++ {
			switch body[p] {
			case '{':
				depth++
				if depth > 1 {
					entry.Reset()
				}
			case '}':
				depth--
				if depth == 1 && entry.Len() > 0 {
					in.addDir(entry.String())
				}
				if depth == 0 {
					p = len(body)
				}
			default:
				if depth > 1 {
					entry.WriteByte(body[p])
				}
			}
			if depth == 0 {
				i = p
				break
			}
			i = p
		}
		if i >= len(body) {
			return
		}
	}
}

func (in *standaloneInliner) addDir(d string) {
	d = strings.TrimSpace(d)
	if d == "" || filepath.IsAbs(d) {
		return
	}
	for _, have := range in.dirs {
		if have == d {
			return
		}
	}
	in.dirs = append(in.dirs, d)
}

// withinRoot 挡住 ../ 越界：单文件版只该内联构建树里的东西。
func withinRoot(root, p string) bool {
	rel, err := filepath.Rel(root, p)
	if err != nil {
		return false
	}
	return rel != ".." && !strings.HasPrefix(rel, ".."+string(filepath.Separator))
}
